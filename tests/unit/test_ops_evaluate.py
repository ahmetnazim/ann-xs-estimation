pytestmark = pytest.mark.unit

LEVEL, TRUNC = 6, 4.0
RKW = {"level": LEVEL, "trunc": TRUNC, "tol": 1e-12, "max_iter": 80, "chunk_rows": 1000}
BOOT = BootstrapParams(b=50, alpha_b=0.05, seed=1, stratify="division")


def _pred(sites: list[str], w: float, d: float, m: float | None, repeats: int = 1) -> pd.DataFrame:
    rows = []
    for rep in range(repeats):
        for s in sites:
            rows.append(
                {
                    "repeat": rep,
                    "site_no": s,
                    "mu_W": math.log(w),
                    "mu_dbar": math.log(d),
                    "mu_dmax": math.log(m) if m is not None else np.nan,
                    "mu_t": math.log(m / d) if m is not None else np.nan,
                }
            )
    return pd.DataFrame(rows)


def test_bin_labels() -> None:
    assert bin_labels([0.0, 0.5, 2.0, float("inf")]) == ["[0,0.5)", "[0.5,2)", "[2,inf)", "high"]


def test_anchor_geometry_fallback_invalid_and_clip() -> None:
    """Fallback shape, invariant-4 failures and r clipping (docs/4 sections 3.1, 3.3)."""
    fb = _pred(["a", "b"], 10.0, 1.0, 1.5)  # t = ln 1.5 -> r = 2
    no_dmax = _pred(["a", "b"], 10.0, 1.0, None)
    g = anchor_geometry(no_dmax, fb, (0.5, 10.0))
    assert g["fallback_shape"].all()
    assert np.allclose(g["r"], 2.0)
    assert np.allclose(np.exp(g["ln_dmax0"]), 1.5)
    with pytest.raises(ValueError, match="no fallback"):
        anchor_geometry(no_dmax, None, (0.5, 10.0))
    bad = _pred(["a"], 10.0, 1.0, 0.9)  # dmax < dbar
    gb = anchor_geometry(bad, None, (0.5, 10.0))
    assert not gb["valid"].iloc[0]
    assert math.isnan(gb["r"].iloc[0])
    flat = _pred(["a"], 10.0, 1.0, 1.01)  # r = 100 -> clipped to 10
    gf = anchor_geometry(flat, None, (0.5, 10.0))
    assert gf["clipped"].iloc[0]
    assert gf["r"].iloc[0] == 10.0


def _obs_from_truth(sites: list[str], w: float, d: float, m: float) -> pd.DataFrame:
    """Observations generated by the true section's own calibrated rating curve."""
    q = np.array([0.3, 0.8, 1.5, 3.0, 7.0, 20.0])
    r = d / (m - d)
    rows = []
    for k, s in enumerate(sites):
        lam, _ = solve_lambda_np(
            np.log(q), np.full(q.size, r), np.full(q.size, math.log(d / w)), **RKW
        )
        dh = stage_change(np.full(q.size, m), lam)
        for i in range(q.size):
            rows.append(
                {
                    "site_no": s,
                    "row_id": 100 * k + i,
                    "division": "east" if k % 2 else "west",
                    "q_ratio": q[i],
                    "ln_q_ratio": math.log(q[i]),
                    "dh_obs": dh[i],
                    "dlnw_obs": lam[i] / r,
                    "dt_years": 0.0,
                }
            )
    return pd.DataFrame(rows)


def test_perfect_model_has_zero_error_and_bins() -> None:
    """A model predicting the true section reproduces the observed responses exactly."""
    sites = ["a", "b", "c"]
    obs = _obs_from_truth(sites, 30.0, 1.0, 1.6)
    geom = anchor_geometry(_pred(sites, 30.0, 1.0, 1.6), None, (0.5, 10.0))
    resp, it = model_responses(obs, geom, **RKW)
    assert it >= 1
    assert np.abs(resp["e_h"]).max() < 1e-10
    assert np.abs(resp["e_w"]).max() < 1e-10
    edges = (0.0, 0.5, 2.0, 5.0, 10.0, float("inf"))
    tab = site_bin_table(resp, edges, 2.0)
    counts = tab.loc[tab["site_no"] == "a"].set_index("bin")["n"].to_dict()
    assert counts == {"[0,0.5)": 1, "[0.5,2)": 2, "[2,5)": 1, "[5,10)": 1, "[10,inf)": 1, "high": 3}


def test_model_responses_empty_when_all_invalid() -> None:
    obs = _obs_from_truth(["a"], 30.0, 1.0, 1.6)
    geom = anchor_geometry(_pred(["a"], 30.0, 1.0, 0.5), None, (0.5, 10.0))
    resp, it = model_responses(obs, geom, **RKW)
    assert resp.empty
    assert it == 0


def _family_inputs(
    n_sites: int = 8,
) -> tuple[pd.DataFrame, dict[str, pd.DataFrame], dict[str, pd.DataFrame], pd.DataFrame]:
    params = load_operational().params
    sites = [f"s{i}" for i in range(n_sites)]
    truth = (30.0, 1.0, 1.6)
    obs = _obs_from_truth(sites, *truth)
    # perfect geometry for M5, 30 % deeper for every other model; M0/M1 use the M3 fallback
    geoms: dict[str, pd.DataFrame] = {}
    tables: dict[str, pd.DataFrame] = {}
    fb = _pred(sites, 30.0, 1.3, 1.3 * 1.6, repeats=2)
    for m in params.predictions.models:
        if m == "M5":
            p = _pred(sites, *truth, repeats=2)
        elif m in ("M0", "M1"):
            p = _pred(sites, 30.0, 1.3, None, repeats=2)
        else:
            p = _pred(sites, 30.0, 1.3, 1.3 * 1.6, repeats=2)
        if m == "M4":  # one invalid site in one repeat -> dropped from the common set
            p.loc[(p["site_no"] == "s0") & (p["repeat"] == 1), "mu_dmax"] = math.log(0.5)
        geoms[m] = anchor_geometry(p, fb, (0.5, 10.0))
        resp, _ = model_responses(obs, geoms[m], **RKW)
        tables[m] = site_bin_table(resp, params.metrics.flow_bin_edges, 2.0)
    og = pd.DataFrame(
        {"site_no": sites, "ln_dmax_obs": math.log(1.6), "ln_dbar_obs": math.log(1.0)}
    )
    return obs, geoms, tables, og


def test_score_family_verdicts_and_common_set() -> None:
    """End-to-end scoring: common set, perfect M5 wins, rankings and verdicts are coherent."""
    params = load_operational().params
    obs, geoms, tables, og = _family_inputs()
    res = score_family("S-ID", obs, geoms, tables, og, params, BOOT)
    assert res["n_common_sites"] == 7  # s0 dropped (M4 invalid in repeat 1)
    assert res["repeats"] == [0, 1]
    assert res["failures"]["M4"]["invalid_share"] == pytest.approx(1 / 16)
    assert res["failures"]["M0"]["fallback_shape"]
    table = pd.DataFrame(res["table"])
    m5 = table.loc[(table["model"] == "M5") & (table["bin"] == HIGH_BIN)].iloc[0]
    assert m5["rmse_h_m"] < 1e-9
    ref = table.loc[table["model"] == "M0"]
    assert np.allclose(ref["skill_h_vs_ref"], 0.0)
    h = res["hypotheses"]
    assert h["H-OPS1"]["verdict"] == "supported (superior)"
    assert h["H-OPS2"]["per_model"]["M5"]["beats_reference"]
    assert h["H-OPS2"]["verdict"] == "falsified"  # deeper models tie M0, cannot beat it
    rank = {r["model"]: r for r in res["ranking"]}
    assert rank["M5"]["rank_geometry"] == 1
    assert rank["M5"]["rank_operational"] == 1
    pre = [c for c in res["contrasts"] if c["pre_registered"]]
    assert {(c["a"], c["b"]) for c in pre} == {("M5", "M2-XGB"), ("M5", "M0"), ("M2-XGB", "M0")}
    assert res["bootstrap"]["b"] == 50


def test_score_family_guards() -> None:
    params = load_operational().params
    obs, geoms, tables, og = _family_inputs(4)
    bad = dict(geoms)
    bad["M3"] = geoms["M3"].loc[geoms["M3"]["repeat"] == 0]
    with pytest.raises(ValueError, match="repeats"):
        score_family("S-ID", obs, bad, tables, og, params, BOOT)
    none_valid = {m: g.assign(valid=False) for m, g in geoms.items()}
    with pytest.raises(ValueError, match="empty common site set"):
        score_family("S-ID", obs, none_valid, tables, og, params, BOOT)


def test_load_predictions(tmp_path: Path) -> None:
    """Filters analysis/family/unit/ablation, fills absent columns and refuses duplicates."""
    base = {
        "analysis": "primary",
        "family": "S-ID",
        "unit": "site",
        "ablation": "",
        "repeat": 0,
        "mu_W": 1.0,
        "mu_dbar": 0.0,
    }
    df = pd.DataFrame(
        [
            {**base, "site_no": "1"},
            {**base, "site_no": "2"},
            {**base, "site_no": "3", "family": "S-LRO"},
            {**base, "site_no": "4", "ablation": "A1"},
        ]
    )
    df.to_parquet(tmp_path / "M0.parquet")
    out = load_predictions(tmp_path, "M0", "S-ID", "primary")
    assert out["site_no"].tolist() == ["1", "2"]
    assert out["mu_dmax"].isna().all()
    with pytest.raises(ValueError, match="no primary/S-IND"):
        load_predictions(tmp_path, "M0", "S-IND", "primary")
    pd.concat([df, df.iloc[:1]]).to_parquet(tmp_path / "M1.parquet")
    with pytest.raises(ValueError, match="duplicated"):
        load_predictions(tmp_path, "M1", "S-ID", "primary")
